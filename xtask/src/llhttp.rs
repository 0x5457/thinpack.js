//! The llhttp wasm payload `node:http` drives, kept in step with the vendored undici bundle.
//!
//! `crates/node/fetch/src/vendor/undici.js` already embeds the wasm build of llhttp that Node
//! parses HTTP/1.1 with. `node:http` registers that payload as a module of its own, so parsing a
//! request does not load the whole undici bundle or select the `fetch` capability. Extracting it
//! here instead of committing a hand-copied blob means a new vendored bundle updates the parser
//! with it.

use std::fs;

const BUNDLE: &str = "crates/node/fetch/src/vendor/undici.js";
const PAYLOAD: &str = "crates/node/http/src/vendor/llhttp-wasm.js";

/// The first `wasmBase64` literal in the bundle is `lib/llhttp/llhttp-wasm.js`, the module built
/// without SIMD instructions, which every supported engine runs.
const MARKER: &str = "var wasmBase64 = \"";

pub(crate) fn sync(check: bool) -> Result<Option<String>, String> {
    let expected = render()?;
    let path = crate::repo_root().join(PAYLOAD);
    if fs::read_to_string(&path).ok().as_deref() == Some(expected.as_str()) {
        return Ok(None);
    }
    if !check {
        fs::write(&path, expected).map_err(|error| format!("{PAYLOAD}: {error}"))?;
    }
    Ok(Some(PAYLOAD.to_owned()))
}

fn render() -> Result<String, String> {
    let bundle = fs::read_to_string(crate::repo_root().join(BUNDLE))
        .map_err(|error| format!("{BUNDLE}: {error}"))?;
    let start = bundle
        .find(MARKER)
        .ok_or_else(|| format!("{BUNDLE}: no wasm payload literal"))?
        + MARKER.len();
    let end = start
        + bundle[start..]
            .find('"')
            .ok_or_else(|| format!("{BUNDLE}: unterminated wasm payload"))?;

    let mut out = String::with_capacity((end - start) + 1024);
    out.push_str(
        "// Generated by `cargo xtask gen` from the vendored undici bundle; do not edit by hand.\n\
         //\n\
         // llhttp is the HTTP/1.1 parser Node.js uses (MIT, https://github.com/nodejs/llhttp),\n\
         // here in the wasm build undici embeds. `llhttp.js` registers and drives it for\n\
         // `node:http`, so neither side parses the protocol on its own.\n\
         'use strict';\n\
         \n\
         module.exports = \"",
    );
    out.push_str(&bundle[start..end]);
    out.push_str("\";\n");
    Ok(out)
}
